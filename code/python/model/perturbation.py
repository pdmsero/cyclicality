"""
perturbation.py
---------------
First-order perturbation of the firm-level R&D model, solved as a genuine
2-state (K̃, a) log-linear system.

This module is a thin wrapper around the **aether-macro** Klein (2000) solver.
The model is defined ONCE, in the Dynare/.mod files under code/dynare/
(generated by code/dynare/gen_mod.py from the project steady state). Both
Dynare 6.5 and aether-macro consume those same files, so the .mod is the single
source of truth and the two engines can be cross-checked against each other
(see code/dynare/engine_crosscheck.py).

Why this replaces the old analytic engine
------------------------------------------
The previous perturbation.py hard-coded a *degenerate* 1-state (a-only) system:
it set revenue = θỸ (linear in own output), so the marginal revenue product of
capital was independent of K̃, the value function was linear in K̃, and capital
never fluctuated. That is exactly the degeneracy the referee flagged ("Claim C").

The fix (approved): keep CRS Cobb-Douglas production, but model the firm as a
monopolistic competitor on the CES demand curve. Perceived real revenue
r̃ = Ȳ^{1/ε}·Ỹ^{(ε-1)/ε} is concave in own output even under CRS, so
MRPK = θα·r̃/K̃ declines in own K̃ and the capital Euler + accumulation make K̃ a
real state. Capital now responds to TFP shocks (the capx accelerator), while
R&D — tied to the smoothed firm value via the R&D FOC — responds much less
(R&D smoothing). The capx-vs-R&D ranking is therefore an endogenous property of
the solved model, not an assertion.

The Klein solution is the recursive law (level deviations from SS, in .mod
declaration order):

    y_t - y_ss = P @ (y_{t-1} - y_ss) + Q @ ε_t,   ε_t ~ N(0, σ_a²)

with all 11 endogenous variables (Y, L, rev, K, I, Z, P, Lam, V, D, a) carried
explicitly. Panel simulation iterates this recursion (see simulation.py).
"""

